#!/usr/bin/env python3
"""v15 replot of SI fig_blocking_vs_depletion on the CORRECTED engine, from Code/sweeps/blocking_test.npz
(regenerated by Code/blocking_test.py). (a) blocked fraction vs mean degree z; (b) recruited (cascade)
fraction vs z; dotted lines = blocking boundary 2/phi. Depletion-ON runs only. CPU, plot only."""
import os
import numpy as np, matplotlib; matplotlib.use("Agg"); import matplotlib.pyplot as plt
plt.rcParams.update({"font.size": 13, "axes.labelsize": 13, "xtick.labelsize": 12,
                     "ytick.labelsize": 12, "legend.fontsize": 11})
HERE = os.path.dirname(os.path.abspath(__file__))
FIGDIR = os.path.join(os.path.dirname(HERE), "figures")      # <repo>/figures in both layouts
try:
    import _paths as _P                                      # public repo: Code/ at repo root
    SW = os.path.join(_P.CODE, "sweeps")
except ImportError:
    SW = os.path.join(os.path.dirname(os.path.dirname(HERE)), "Code", "sweeps")  # project layout

F = np.load(os.path.join(SW, "blocking_test.npz"))
z, ths = F["z"], F["thetas"]
fig, ax = plt.subplots(1, 2, figsize=(11.5, 4.2))
for th in ths:
    tag = f"th{th:.2f}_dep"
    col = "#d94f3d" if th < 0.25 else "#5b8def"
    ax[0].plot(z, F[f"{tag}_blocked_frac"], "-o", color=col, ms=4, label=rf"$\phi={th:.2f}$")
    ax[1].plot(z, F[f"{tag}_casc_frac"], "-o", color=col, ms=4, label=rf"$\phi={th:.2f}$")
    for a in ax:
        a.axvline(2 / th, ls=":", color=col, lw=1.2, alpha=0.7)
ax[0].set_ylabel("blocked fraction")
ax[1].set_ylabel("recruited (cascade) fraction")
for a in ax:
    a.set_xscale("log")
    a.set_xlabel(r"mean degree $z$   (dotted = blocking boundary $2/\phi$)")
    a.legend(frameon=False)
ax[0].set_title("(a)", loc="left", fontweight="bold")
ax[1].set_title("(b)", loc="left", fontweight="bold")
fig.tight_layout()
fig.savefig(os.path.join(FIGDIR, "fig_blocking_vs_depletion.pdf"), bbox_inches="tight")
print("wrote fig_blocking_vs_depletion.pdf | phi=0.18 blocked %.2f->%.2f | phi=0.30 blocked %.2f->%.2f"
      % (F["th0.18_dep_blocked_frac"][0], F["th0.18_dep_blocked_frac"][-1],
         F["th0.30_dep_blocked_frac"][0], F["th0.30_dep_blocked_frac"][-1]))
