#!/usr/bin/env python3
"""v15 replot of SI fig_patch_lifecycle on the CORRECTED engine, from Code/sweeps/patch_rw_th*.npz
(regenerated by Code/patch_lifecycle_test.py). (a) giving-up-density histogram at phi=0.20; (b) blocking-
driven fraction of departures vs phi, with Wilson 95% CI. CPU, plot only."""
import os, glob
import numpy as np, matplotlib; matplotlib.use("Agg"); import matplotlib.pyplot as plt
plt.rcParams.update({"font.size": 13, "axes.labelsize": 13, "xtick.labelsize": 12,
                     "ytick.labelsize": 12, "legend.fontsize": 11})
HERE = os.path.dirname(os.path.abspath(__file__))
FIGDIR = os.path.join(os.path.dirname(HERE), "figures")      # <repo>/figures in both layouts
try:
    import _paths as _P                                      # public repo: Code/ at repo root
    SW = os.path.join(_P.CODE, "sweeps")
except ImportError:
    SW = os.path.join(os.path.dirname(os.path.dirname(HERE)), "Code", "sweeps")  # project layout


def wilson(k, n, z=1.96):
    if n <= 0:
        return 0.0, 0.0
    p = k / n
    d = 1 + z * z / n
    c = (p + z * z / (2 * n)) / d
    h = z * np.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / d
    return max(0.0, c - h), min(1.0, c + h)


fig, ax = plt.subplots(1, 2, figsize=(10, 3.9))

d = np.load(os.path.join(SW, "patch_rw_th0.20.npz"))
gud = d["gud"]
med = float(np.median(gud))
ax[0].hist(gud, bins=np.linspace(0, 1, 21), color="#2e7d32", alpha=0.8, edgecolor="white")
ax[0].axvline(med, color="k", ls="--", lw=1.5)
ax[0].text(med + 0.03, ax[0].get_ylim()[1] * 0.88, f"median\n{med:.2f}", fontsize=11)
ax[0].axvline(0, color="#c0392b", ls=":", lw=1.5)
ax[0].text(0.02, ax[0].get_ylim()[1] * 0.5, "drained\n($\\approx$0)", color="#c0392b", fontsize=10)
ax[0].set_xlabel("resource remaining at departure  (giving-up density)")
ax[0].set_ylabel("number of patches")
ax[0].set_title("(a)", loc="left", fontweight="bold")

ths, fr, lo, hi, n20 = [], [], [], [], None
for f in sorted(glob.glob(os.path.join(SW, "patch_rw_th*.npz"))):
    dd = np.load(f)
    th = float(os.path.basename(f).split("th")[-1].replace(".npz", ""))
    n, k, p = float(dd["n_dep"]), float(dd["rev_blocked"]), float(dd["blocked_release_frac"])
    l, h = wilson(k, n)
    ths.append(th); fr.append(p); lo.append(p - l); hi.append(h - p)
    if abs(th - 0.20) < 1e-6:
        n20 = int(n)
o = np.argsort(ths)
ths, fr = np.array(ths)[o], np.array(fr)[o]
lo, hi = np.array(lo)[o], np.array(hi)[o]
ax[1].errorbar(ths, fr, yerr=[lo, hi], fmt="o-", color="#1f77b4", ms=7, lw=2, capsize=3)
ax[1].set_ylim(-0.03, 1.0)
ax[1].set_xlabel(r"recruitment threshold $\phi$")
ax[1].set_ylabel("fraction of departures\ncaused by blocking")
ax[1].set_title("(b)", loc="left", fontweight="bold")

fig.tight_layout()
fig.savefig(os.path.join(FIGDIR, "fig_patch_lifecycle.pdf"), bbox_inches="tight")
print("wrote fig_patch_lifecycle.pdf | median GUD=%.2f | n_dep(phi=0.20)=%d | blocked-frac vs phi: %s"
      % (med, n20, list(zip(ths.round(2), fr.round(2)))))
